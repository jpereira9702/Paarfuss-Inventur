test('Bestellvermerk, Teillieferung und Reststorno erhalten beide Bestände korrekt', async ({ page }) => {
  await start(page)
  await nav(page, 'Nachbestellen').click()
  const artikel = karte(page)
  await expect(artikel).toContainText('Noch nachbestellen: 12 Flasche')
  await expect(artikel).toContainText('Kematen hat 12 Flasche über dem Zielbestand')
  await artikel.getByText('Externe Bestellung vermerken', { exact: true }).click()
  await artikel.getByRole('button', { name: 'Als bestellt vermerken' }).click()
  await expect(artikel).toContainText('Noch nachbestellen: 0 Flasche')
  await expect(artikel).toContainText('Bestand: 2')
  await artikel.getByLabel('Jetzt geliefert (Flasche)').fill('5')
  page.once('dialog', d => d.accept())
  await artikel.getByRole('button', { name: 'Lieferung buchen', exact: true }).click()
  await expect(artikel).toContainText('5 geliefert · 7 offen')
  await expect(artikel).toContainText('Bestand: 7')
  await page.reload()
  await nav(page, 'Nachbestellen').click()
  await expect(artikel).toContainText('5 geliefert · 7 offen')
  page.once('dialog', d => d.accept())
  await artikel.getByRole('button', { name: 'Rest stornieren' }).click()
  await expect(artikel).toHaveCount(0)
  const daten = await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)
  expect(daten.produkte[0].lager.innsbruck.bestand).toBe(7)
  expect(daten.produkte[0].lager.kematen.bestand).toBe(20)
  expect(daten.bestellungen[0].storniert).toBe(true)
})
