import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { altbestandZuordnen, bestellungMerken, filialeAendern } from '../../src/data/filialen.js'
import { inventurStarten, leereInventur, produktSpeichern } from '../../src/data/inventur.js'
const key = 'paarfuss.react.v1'
const alt = { produkte: [{ artikelnummer: 'FC-1', barcode: '4006381333931', name: 'Creme', bestand: 2, mindestbestand: 5, zielbestand: 12, packung: 6, einheit: 'Flasche' }], inventur: leereInventur() }
const basis = () => filialeAendern(altbestandZuordnen(alt, 'innsbruck'), 'kematen', d => produktSpeichern(d, { ...d.produkte[0], bestand: 20, mindestbestand: 3, zielbestand: 8 }, 'FC-1'))
const bestellt = () => bestellungMerken(basis(), { produktId: 'FC-1', filiale: 'innsbruck', anzahl: 12, datum: '2026-09-30' }, 'B1')
const nav = (page, name) => page.getByRole('navigation').getByRole('button', { name, exact: true })
const karte = page => page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Creme · Innsbruck', exact: true }) })
async function start(page, daten = basis()) {
  await page.goto('/')
  await page.evaluate(({ key, daten }) => localStorage.setItem(key, JSON.stringify(daten)), { key, daten })
  await page.reload()
}
const browserFehler = new WeakMap()
test.beforeEach(async ({ page }) => {
  browserFehler.set(page, [])
  page.on('pageerror', error => browserFehler.get(page).push(error.message))
})
test.afterEach(async ({ page }) => { expect(browserFehler.get(page)).toEqual([]) })

test('Altbestand erfordert bewusste Filialwahl und bleibt bis dahin unberührt', async ({ page }) => {
  await start(page, alt)
  await expect(page.getByRole('button', { name: 'Bestand zuordnen', exact: true })).toBeDisabled()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)).toEqual(alt)
  await page.getByLabel('Filiale des bisherigen Bestands').selectOption('kematen')
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Bestand zuordnen', exact: true }).click()
  await expect(page.getByLabel('Aktive Filiale')).toHaveValue('kematen')
  await nav(page, 'Lager').click()
  await expect(page.getByRole('article')).toContainText('Bestand: 2')
  await page.getByLabel('Aktive Filiale').selectOption('innsbruck')
  await expect(page.getByRole('article')).toContainText('Bestand: 0')
})
