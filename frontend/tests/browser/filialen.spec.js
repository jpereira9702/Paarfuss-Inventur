test('Sicherung unter Einstellungen enthält beide Lager, Inventuren und Bestellungen', async ({ page }) => {
  const daten = filialeAendern(bestellt(), 'kematen', inventurStarten)
  await start(page, daten)
  await nav(page, 'Start').click()
  await expect(page.getByRole('button', { name: 'Daten exportieren', exact: true })).toHaveCount(0)
  await nav(page, 'Einstellungen').click()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Daten exportieren', exact: true }).click()
  const datei = await download
  const sicherung = JSON.parse(await readFile(await datei.path(), 'utf8'))
  expect(sicherung).toEqual(daten)
  await page.getByLabel('JSON-Sicherung importieren').setInputFiles({ name: 'filialen.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(sicherung)) })
  await expect(page.getByLabel('Filiale des importierten Bestands')).toHaveCount(0)
  page.once('dialog', d => d.accept())
  await page.getByRole('button', { name: 'Daten ersetzen', exact: true }).click()
  expect(await page.evaluate(key => JSON.parse(localStorage.getItem(key)), key)).toEqual(daten)
})
